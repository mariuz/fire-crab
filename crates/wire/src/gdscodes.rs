/// Whether `name` (any case) is a known status-code symbol.
pub fn is_gds_code(name: &str) -> bool {
    entry_by_name(name).is_some()
}

/// The entry a `WHEN GDSCODE <name>` condition names.
pub fn entry_by_name(name: &str) -> Option<&'static GdsCode> {
    let up = name.to_ascii_uppercase();
    GDS_CODES
        .binary_search_by(|e| e.name.cmp(up.as_str()))
        .ok()
        .map(|i| &GDS_CODES[i])
}

/// What a raised gdscode IS - its SQLCODE and SQLSTATE.
pub fn entry_by_code(gds: i32) -> Option<&'static GdsCode> {
    BY_CODE
        .binary_search_by(|i| GDS_CODES[*i as usize].gds.cmp(&gds))
        .ok()
        .map(|i| &GDS_CODES[BY_CODE[i] as usize])
}

/// `isc_random` and `isc_sqlerr` - the two the SQLSTATE walk skips.
const RANDOM: i32 = 335544382;
const SQLERR: i32 = 335544436;

/// THE SQLSTATE OF A WHOLE STATUS VECTOR, as `fb_sqlstate`
/// (yvalve/gds.cpp:2464) derives it - which is what `WHEN SQLSTATE`
/// compares against and what a client prints on its "Statement failed"
/// line.
///
/// It is NOT the first code's SQLSTATE. The walk skips `isc_random`
/// (whose message is just "@1") and `isc_sqlerr`, ignores an entry of
/// "00000", and - the part that matters - **keeps scanning past the
/// GENERAL states 22000, 42000 and HY000 in the hope of something more
/// specific**. So an integer division by zero, which posts
/// `isc_arith_except` (22000, general) followed by
/// `isc_exception_integer_divide_by_zero` (22012), is 22012 - and
/// `WHEN SQLSTATE '22000'` does NOT catch it, while `WHEN GDSCODE
/// arith_except` does, because GDSCODE matches only the FIRST code.
///
/// "HY000" when nothing more specific is found, as the engine's error
/// of last resort.
pub fn sqlstate_of(codes: &[i32]) -> &'static str {
    let mut state = "HY000";
    for c in codes {
        if *c == RANDOM || *c == SQLERR {
            continue;
        }
        let Some(e) = entry_by_code(*c) else { continue };
        if e.sqlstate == "00000" {
            continue;
        }
        state = e.sqlstate;
        if !matches!(e.sqlstate, "22000" | "42000" | "HY000") {
            break; // exact - stop looking
        }
    }
    state
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_agrees_with_the_engines_headers() {
        let arith = entry_by_name("arith_except").unwrap();
        assert_eq!((arith.gds, arith.sqlcode, arith.sqlstate), (335544321, -802, "22000"));
        // isc_except: what every raised user exception leads with
        let except = entry_by_name("EXCEPT").unwrap();
        assert_eq!((except.gds, except.sqlcode, except.sqlstate), (335544517, -836, "HY000"));
        assert!(!is_gds_code("no_such_code"));
        assert_eq!(entry_by_code(335544321).unwrap().name, "ARITH_EXCEPT");
    }

    #[test]
    fn sqlstate_keeps_scanning_past_the_general_ones() {
        // divide by zero: arith_except (22000, general) then the
        // specific one - the engine reports 22012
        assert_eq!(sqlstate_of(&[335544321, 335544778]), "22012");
        // a user exception is isc_except + isc_random(s): HY000, and the
        // random items must not drag it anywhere
        assert_eq!(sqlstate_of(&[335544517, 335544382, 335544382]), "HY000");
        // nothing recognised at all is still the error of last resort
        assert_eq!(sqlstate_of(&[]), "HY000");
        assert_eq!(sqlstate_of(&[424242]), "HY000");
    }
}
