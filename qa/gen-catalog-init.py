#!/usr/bin/env python3
"""Port the engine's initial-catalog skeleton tables to Rust.

Reads src/jrd/{names,fields,relations}.h from the vendored engine and
emits crates/ods/src/catalog_init.rs: the system names, global fields
and relations with every macro resolved to its value. Rerun when the
engine sources change; do not edit the output by hand.

Usage: qa/gen-catalog-init.py [engine-dir]   (default: ../../firebird)
"""
import re
import sys
from pathlib import Path

ENGINE = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent / "../../firebird")
JRD = ENGINE / "src/jrd"

DTYPE = {"dtype_text": 1, "dtype_cstring": 2, "dtype_varying": 3,
         "dtype_packed": 6, "dtype_byte": 7, "dtype_short": 8,
         "dtype_long": 9, "dtype_quad": 10, "dtype_real": 11,
         "dtype_double": 12, "dtype_d_float": 13, "dtype_sql_date": 14,
         "dtype_sql_time": 15, "dtype_timestamp": 16, "dtype_blob": 17,
         "dtype_array": 18, "dtype_int64": 19, "dtype_dbkey": 20,
         "dtype_boolean": 21, "dtype_dec64": 22, "dtype_dec128": 23,
         "dtype_int128": 24, "dtype_sql_time_tz": 25, "dtype_timestamp_tz": 26}
SIZEOF = {"SSHORT": 2, "SLONG": 4, "SINT64": 8, "FLOAT": 4, "double": 8}
CONSTS = {"BLOB_SIZE": 8, "TIMESTAMP_SIZE": 8, "TIMESTAMP_TZ_SIZE": 12,
          "METADATA_BYTES_PER_CHAR": 4, "METADATA_IDENTIFIER_CHAR_LEN": 63,
          "MAX_SQL_IDENTIFIER_LEN": 252, "MAX_CONFIG_NAME_LEN": 63,
          "USERNAME_LENGTH": 252, "MAX_COLUMN_SIZE": 32767,
          "MAX_VARY_COLUMN_SIZE": 32765}
SUBTYPE = {"dsc_text_type_fixed": 1, "dsc_text_type_ascii": 2,
           "dsc_text_type_metadata": 3, "isc_blob_untyped": 0,
           "isc_blob_text": 1, "isc_blob_blr": 2, "isc_blob_acl": 3,
           "isc_blob_ranges": 4, "isc_blob_summary": 5, "isc_blob_format": 6,
           "isc_blob_tra": 7, "isc_blob_extfile": 8, "isc_blob_debug_info": 9}
# dflt.h, resolved (blr_version5=5, literal=21, text2=15, eoc=76;
# ttype_ascii=2, ttype_binary=1)
DFLT = {"dflt_no": [5, 21, 15, 2, 0, 2, 0, 78, 79, 76],
        "dflt_full": [5, 21, 15, 2, 0, 4, 0, 70, 85, 76, 76, 76],
        "dflt_restrict": [5, 21, 15, 2, 0, 8, 0, 82, 69, 83, 84, 82, 73, 67, 84, 76],
        "dflt_no_privs": [5, 21, 15, 1, 0, 8, 0, 0, 0, 0, 0, 0, 0, 0, 0, 76]}


def macro_args(line):
    return [a.strip() for a in line[line.index("(") + 1: line.rindex(")")].split(",")]


def num(expr):
    expr = expr.strip()
    m = re.fullmatch(r"sizeof\((\w+)\)", expr)
    if m:
        return SIZEOF[m.group(1)]
    if re.fullmatch(r"-?\d+", expr):
        return int(expr)
    if expr in CONSTS:
        return CONSTS[expr]
    # left-associative a op b op c over terms above
    toks = re.findall(r"\w+|[*/]", expr)
    val = num(toks[0])
    i = 1
    while i < len(toks):
        rhs = num(toks[i + 1])
        val = val * rhs if toks[i] == "*" else val // rhs
        i += 2
    return val


def main():
    names = {}
    for line in (JRD / "names.h").read_text().splitlines():
        if line.strip().startswith("NAME("):
            s, k = macro_args(line)
            assert s.startswith('"') and k not in names, line
            names[k] = s.strip('"')

    fields = []
    for line in (JRD / "fields.h").read_text().splitlines():
        if line.strip().startswith("FIELD("):
            key, nam, dt, ln, st, df, nl, _ods = macro_args(line)
            stv = SUBTYPE[st] if st in SUBTYPE else int(st)
            fields.append((key, names[nam], DTYPE[dt], num(ln), stv,
                           None if df == "NULL" else DFLT[df],
                           nl == "true"))

    relations = []
    cur = None
    for line in (JRD / "relations.h").read_text().splitlines():
        s = line.strip()
        if s.startswith("RELATION("):
            _nam, _rel, _ods, kind = macro_args(line)
            cur = (_nam, kind == "rel_persistent", [])
            relations.append(cur)
        elif s.startswith("FIELD("):
            _f, nam, fld, upd, _ods = macro_args(line)
            cur[2].append((names[nam], fld, upd == "1"))
    fld_names = {k: n for k, n, *_ in fields}
    assert all(f in fld_names for _, _, fl in relations for _, f, _ in fl)

    gkeys = {}
    for key, *_ in fields:
        gkeys.setdefault(key, key)

    out = []
    w = out.append
    w("//! The engine's initial-catalog skeleton tables: system names, global")
    w("//! fields and relations (`src/jrd/{names,fields,relations}.h`), every")
    w("//! macro resolved to its value. Generated by `qa/gen-catalog-init.py`;")
    w("//! do not edit by hand. Content pinned against the reference template's")
    w("//! RDB$ rows in the tests below.")
    w("")
    w("/// A global field (`fields.h`): its RDB$FIELDS name, dtype, length,")
    w("/// subtype, default BLR and nullability.")
    w("pub struct SysFieldDef {")
    w("    pub key: &'static str,")
    w("    pub name: &'static str,")
    w("    pub dtype: u8,")
    w("    pub length: u16,")
    w("    pub sub_type: i16,")
    w("    pub default: Option<&'static [u8]>,")
    w("    pub nullable: bool,")
    w("}")
    w("")
    for key, d in sorted(DFLT.items()):
        w("const %s: &[u8] = &[%s];" % (key.upper(), ", ".join(map(str, d))))
    w("")
    w("/// The %d global fields, in `fields.h` order." % len(fields))
    w("pub const SYS_FIELDS: &[SysFieldDef] = &[")
    for key, name, dt, ln, st, df, nl in fields:
        d = "None" if df is None else "Some(%s)" % next(k.upper() for k, v in DFLT.items() if v == df)
        w('    SysFieldDef { key: "%s", name: "%s", dtype: %d, length: %d, sub_type: %d, default: %s, nullable: %s },'
          % (key, name, dt, ln, st, d, str(nl).lower()))
    w("];")
    w("")
    w("/// One relation field: its RDB$RELATION_FIELDS name, its global field")
    w("/// (`SysFieldDef.key`) and the update flag.")
    w("pub struct SysRelField {")
    w("    pub name: &'static str,")
    w("    pub global: &'static str,")
    w("    pub update: bool,")
    w("}")
    w("")
    w("/// A system relation: its RDB$RELATIONS id (file order), name,")
    w("/// persistence and fields.")
    w("pub struct SysRelation {")
    w("    pub id: u16,")
    w("    pub name: &'static str,")
    w("    pub persistent: bool,")
    w("    pub fields: &'static [SysRelField],")
    w("}")
    w("")
    seen = set()
    for i, (nam, _p, fl) in enumerate(relations):
        c = "REL_%s_FIELDS" % names[nam].replace("$", "_")
        assert c not in seen, c
        seen.add(c)
        w("const %s: &[SysRelField] = &[" % c)
        for fn, fg, up in fl:
            w('    SysRelField { name: "%s", global: "%s", update: %s },' % (fn, fg, str(up).lower()))
        w("];")
    w("")
    w("/// The %d system relations, in `relations.h` order (file order is the id)." % len(relations))
    w("pub const SYS_RELATIONS: &[SysRelation] = &[")
    for i, (nam, p, fl) in enumerate(relations):
        c = "REL_%s_FIELDS" % names[nam].replace("$", "_")
        w('    SysRelation { id: %d, name: "%s", persistent: %s, fields: %s },'
          % (i, names[nam], str(p).lower(), c))
    w("];")
    w("")
    target = Path(__file__).resolve().parent / "../crates/ods/src/catalog_init.rs"
    target.write_text("\n".join(out) + "\n")
    print("wrote %s: %d names, %d fields, %d relations" % (target, len(names), len(fields), len(relations)))


main()
