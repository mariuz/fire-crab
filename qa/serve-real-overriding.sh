kill $srv 2>/dev/null; wait $srv 2>/dev/null
echo "--- 12. final differential, gbak and gfix"

dump() { # <file>
    "$ISQL" -q -b -user "$U" -pas "$P" "$1" 2>&1 <<'SQL' | strip | grep -v '^$'
SET HEADING OFF;
SELECT 'TA|'||ID||'|'||COALESCE(TRIM(B),'~') FROM TA ORDER BY ID;
SELECT 'TD|'||ID||'|'||COALESCE(TRIM(B),'~') FROM TD ORDER BY ID;
SELECT 'TA2|'||ID||'|'||COALESCE(TRIM(B),'~') FROM S1.TA2 ORDER BY ID;
SELECT 'TZ3|'||ID||'|'||COALESCE(TRIM(B),'~') FROM S1.TZ3 ORDER BY ID;
SELECT 'PLAIN|'||COALESCE(CAST(A AS VARCHAR(12)),'~') FROM PLAIN ORDER BY 1;
SELECT 'PT|'||COALESCE(CAST(A AS VARCHAR(12)),'~')||'|'||COALESCE(TRIM(B),'~') FROM PT ORDER BY 1;
SELECT 'DDEF|'||COALESCE(CAST(A AS VARCHAR(12)),'~')||'|'||COALESCE(TRIM(B),'~') FROM D_DEF ORDER BY 1;
SELECT 'DNODEF|'||COALESCE(CAST(A AS VARCHAR(12)),'~') FROM D_NODEF;
SELECT 'DNN|'||COUNT(*) FROM D_NN;
SELECT 'DNNDEF|'||COALESCE(CAST(A AS VARCHAR(12)),'~') FROM D_NNDEF;
SELECT 'DCOMP|'||A||'|'||C FROM D_COMP ORDER BY 1;
SELECT 'DPK|'||A FROM D_PK ORDER BY 1;
SELECT 'CMP|'||A||'|'||C||'|'||TRIM(B) FROM CMP ORDER BY 1;
SELECT 'POSN|'||P1||'|'||P2||'|'||P3 FROM POSN;
SELECT 'GEN|'||GEN_ID(RDB$1,0)||'|'||GEN_ID(RDB$2,0) FROM RDB$DATABASE;
SELECT 'S1GEN|'||GEN_ID(S1.RDB$4,0)||'|'||GEN_ID(S1.RDB$5,0) FROM RDB$DATABASE;
SQL
}
work_d=$(dump "$WORK")
check "every table and both generators match the engine's own file" \
      "$work_d" "$(dump "$REF")"
# the comparison must not be vacuous: the load-bearing rows really landed
case "$work_d" in
    *"TA|1005|AL_EXPL_OS"*"TA|7001|s1"*"TA2|3006|q6"*"DCOMP|3|30"*"POSN|10|20|30"*)
        echo "OK   the content comparison is not vacuous (OSV literals in PUBLIC and in S1, INSERT..SELECT rows, POSN order, computed column)" ;;
    *) echo "DIFF the content comparison was vacuous"; echo "     $work_d"; fail=1 ;;
esac
checks=$((checks + 1))

if "$GBAK" -b -g -user "$U" -pas "$P" "$WORK" "$FBK" >/tmp/fc-ovr-backup.log 2>&1; then
    echo "OK   gbak backs up the database fire-crab wrote"
else
    echo "DIFF gbak backup"; cat /tmp/fc-ovr-backup.log; fail=1
fi
checks=$((checks + 1))
"$GBAK" -c -user "$U" -pas "$P" "$FBK" "$RST" >/tmp/fc-ovr-restore.log 2>&1
rc=$?
checks=$((checks + 1))
if [ $rc -eq 0 ] && ! grep -qiE "error" /tmp/fc-ovr-restore.log; then
    echo "OK   gbak RESTORES it"
else
    echo "DIFF gbak restore (exit $rc)"; grep -iE "error|cannot" /tmp/fc-ovr-restore.log | head; fail=1
fi
valw=$("$GFIX" -v -full -user "$U" -pas "$P" "$WORK" 2>&1)
check "gfix -v -full clean (fc's raw file)" "$(printf '%s' "$valw" | strip)" ""

echo "--- $checks differential checks, $bounds recorded boundaries"
exit $fail
