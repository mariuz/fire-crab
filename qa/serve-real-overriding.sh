# ======================================================================
# 11. The priced boundaries. Each records what the engine does so the
#     next slice has its target.
# ======================================================================
echo "--- 11. recorded boundaries (fire-crab refuses; the engine answers)"
# the engine describes these from the INSERT TARGET COLUMN: 496 LONG /
# 448 VARYING len 10 / 570 SQL DATE / 496 LONG scale -3 subtype 1, and
# the nullability bit is the target column's too
# NOTE: a `bound` statement runs on the ENGINE too, and the engine
# ANSWERS it - so every one of them targets BND / BCMP / BID, the three
# tables the final content differential deliberately does not dump.
# Pointing them at PT or D_DEF would silently desynchronise the twins.
bound "select-list ? (engine types it from the TARGET column: 496 LONG + 448 VARYING len 10)" \
      "INSERT INTO BND (A,B) SELECT ?, ? FROM SRC" '[1,"z"]'
bound "select-list ? mixed with a WHERE ? (engine: 01 target BND.A, 02 SRC.X)" \
      "INSERT INTO BND (A,B) SELECT ?, Y FROM SRC WHERE X = ?" '[1,7001]'
bound "? + 1 in the select list (engine keeps the target typing: 496 LONG)" \
      "INSERT INTO BND (A,B) SELECT ? + 1, Y FROM SRC" '[1]'
bound "CAST(? AS SMALLINT) in the select list (engine: 500 SHORT len 2)" \
      "INSERT INTO BND (A,B) SELECT CAST(? AS SMALLINT), Y FROM SRC" '[1]'
bound "MERGE ... WHEN NOT MATCHED THEN INSERT ... OVERRIDING (no MERGE surface at all)" \
      "MERGE INTO BID USING SRC ON BID.ID = SRC.X WHEN NOT MATCHED THEN INSERT (ID,B) OVERRIDING SYSTEM VALUE VALUES (SRC.X, SRC.Y)"
bound "RETURNING * (returning_ident cannot parse '*')" \
      "INSERT INTO BND DEFAULT VALUES RETURNING *"
bound "RETURNING a COMPUTED column (engine evaluates it; fc would answer null-flag bytes)" \
      "INSERT INTO BCMP DEFAULT VALUES RETURNING A, C"
# both error, different vector: fire-crab has no -804 surface
both "? = ? in the source refuses on BOTH (engine -804/HY004, fc generic)" \
     "INSERT INTO BND (A,B) SELECT X, Y FROM SRC WHERE ? = ?" '[1,1]' 1

# ======================================================================
# 11b. A VIEW target. fire-crab has no view-INSERT surface - a priced
#      boundary. What it must NOT do is answer the identity check first:
#      a view carries no identity column of its own, so the metadata rule
#      would confidently ship 335545134 naming the VIEW, where the engine
#      merges the view and writes the BASE table. And when the engine DOES
#      refuse through a view it names the BASE table, so even the argument
#      would be wrong. The typed verdict is therefore a TABLE verdict; a
#      view target falls through to the generic refusal below. VBASE is
#      deliberately absent from the final content dump - the engine
#      ANSWERS these, so the twins part company here.
# ======================================================================
echo "--- 11b. a view target ships no typed identity verdict"
bound "OSV into a view (engine merges and writes VBASE; fc has no view-INSERT surface)" \
      "INSERT INTO VTA (ID,B) OVERRIDING SYSTEM VALUE VALUES (4444,'v9')"
bound "a plain view INSERT naming the identity (the engine's 335545137 names \"PUBLIC\".\"VBASE\")" \
      "INSERT INTO VTA (ID,B) VALUES (3007,'v1')"
bound "a view INSERT omitting the identity (engine: the base generator draws)" \
      "INSERT INTO VTA (B) VALUES ('v2')"
vview=$(run "$PORT" "$WORK" "INSERT INTO VTA (ID,B) OVERRIDING SYSTEM VALUE VALUES (4445,'v10')")
check "the refusal is GENERIC - it used to fabricate 335545134 \"PUBLIC\".\"VTA\"" \
      "$vview" 'ERR [{"gdscode":335544569}]'
check "and the view's BASE table is untouched on fire-crab's side" \
      "$(col "$WORK" "SELECT COUNT(*) FROM VBASE")" "0"

